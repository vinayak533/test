/* ============================================================================
   sync_i18n_inline.js — regenerates the i18n bootstrap inside the HTML.

   The dropdown and every fixed label in the panel come from misty_i18n.js.
   When that file does not reach the page — opened on its own, copied without
   its siblings, served from somewhere the script tag cannot follow — the
   dropdown collapses to English and each label falls back to its key, which
   is what put "tabHome" and "tabChat" on screen instead of "Home" and "Chat".

   So LANGS and UI — the two small datasets, about 32 KB of the 217 — are
   copied into the page itself between the markers below, ahead of the script
   tag. If misty_i18n.js does load it replaces window.MM_I18N wholesale and
   nothing here is consulted; if it does not, the panel still speaks all four
   languages and only the long-form answers fall back to English.

   Run after editing LANGS or UI in misty_i18n.js:

       node sync_i18n_inline.js
   ============================================================================ */

const fs = require("fs");

const BEGIN = "<!-- BEGIN i18n bootstrap · generated by sync_i18n_inline.js · do not edit by hand -->";
const END   = "<!-- END i18n bootstrap -->";

global.window = {};
require("./misty_i18n.js");
const { LANGS, UI } = global.window.MM_I18N;

/* A "</script" anywhere in the data would close the tag early. Nothing in the
   pack carries one today; splitting the sequence keeps it that way for good. */
const json = v => JSON.stringify(v, null, 1).replace(/<\/script/gi, '<\/script');

const block = [
  BEGIN,
  "<script>",
  "/* Copied from misty_i18n.js. Regenerate with `node sync_i18n_inline.js`. */",
  "(function (root) {",
  "  root.MM_I18N = {",
  "    LANGS: " + json(LANGS) + ",",
  "    UI: " + json(UI) + ",",
  "    DATA: {}, REPLY: {}, TERMS: {}",
  "  };",
  "}(window));",
  "</" + "script>",
  END
].join("\n");

const F = "index.html";
let html = fs.readFileSync(F, "utf8");

const i = html.indexOf(BEGIN), j = html.indexOf(END);
if (i !== -1 && j !== -1) {
  html = html.slice(0, i) + block + html.slice(j + END.length);
} else {
  const anchor = '<script src="misty_i18n.js"></' + 'script>';
  if (!html.includes(anchor)) { console.error("anchor not found: " + anchor); process.exit(1); }
  html = html.replace(anchor, block + "\n" + anchor);
}

fs.writeFileSync(F, html);
console.log(`bootstrap written: ${LANGS.length} languages, ${Object.keys(UI.en).length} keys, ${(block.length / 1024).toFixed(1)} KB`);
